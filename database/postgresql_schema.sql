DECLARE
  table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'lineas_producto', 'matrices', 'clientes', 'comerciales', 'usuarios',
    'solicitudes_servicio', 'reglamentos_catalogo', 'catalogo_productos_reglamentarios',
    'notificaciones_correo', 'proyectos', 'proyecto_items', 'laboratorios',
    'criterios_precotizacion', 'precotizaciones'
  ]
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', 'trg_' || table_name || '_actualizado_en', table_name);
